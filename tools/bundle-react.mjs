#!/usr/bin/env node
// @ts-check
/**
 * dsh-hud — build `media/react.js`, the React runtime the webview runs.
 *
 * The browser half is the vendor's own `hud/client.js`, byte for byte, and it
 * is a DSH module-loader bundle: a single
 * `window.__ModuleLoader__.load({ id, factory: (require) => exports })` call
 * whose factory does exactly two `require`s —
 *
 *     const { jsx, jsxs } = require('react/jsx-runtime')
 *     const React = require('react')
 *
 * A VS Code webview has no such module table, so this bundles the two modules
 * into one classic script that publishes them on `globalThis.__hudReact`. The
 * loader shim in `media/runtime.js` hands them to the factory unchanged; the
 * bundle itself is never edited.
 *
 * `jsx-runtime` is bundled from its REAL source rather than reimplemented over
 * `React.createElement`: the two differ in how they treat `key`, `ref` and
 * `children`, and a hand-written stand-in would render subtly different trees.
 *
 *   node tools/bundle-react.mjs
 */

import { mkdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(root, 'tools', 'react-entry.js')
const OUT = join(root, 'media', 'react.js')

// The entry is generated here so the bundle has a single, obvious seam: it
// pulls in the three module namespaces and nothing else.
const entrySource = `// GENERATED by tools/bundle-react.mjs — the webview's React runtime.
import * as React from 'react'
import * as jsxRuntime from 'react/jsx-runtime'
import * as ReactDOMClient from 'react-dom/client'

globalThis.__hudReact = {
  React: React.default ?? React,
  jsxRuntime,
  ReactDOMClient,
}
`
mkdirSync(dirname(ENTRY), { recursive: true })
writeFileSync(ENTRY, entrySource, 'utf8')

await build({
  entryPoints: [ENTRY],
  outfile: OUT,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome110'],
  minify: true,
  /**
   * React and ReactDOM are MIT: the licence and copyright notice have to travel
   * with every copy, and a minified bundle is still a copy. `'none'` stripped the
   * `@license` headers, which is the one thing a redistributor may not do — so
   * they are kept (at the end, where they cost nothing) and the banner below
   * states plainly what this file contains and under what terms.
   */
  legalComments: 'eof',
  banner: {
    js: [
      '/*!',
      ' * dsh-hud — the webview\'s React runtime, generated by tools/bundle-react.mjs.',
      ' *',
      ' * Bundles, unmodified:',
      ' *   react, react-dom (react/jsx-runtime) — MIT, Copyright (c) Meta Platforms, Inc. and affiliates',
      ' *',
      ' * Full texts: THIRD-PARTY-NOTICES.md in this extension, and the @license',
      ' * comments esbuild appends below.',
      ' */',
    ].join('\n'),
  },
  // React's PRODUCTION build: the development one is ~3x larger and its
  // warnings are already asserted against by the vendor's own jsdom suite
  // (`hud/tools/test-client.mjs` runs the bundle under dev React).
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
})

const bytes = statSync(OUT).size
console.log(`media/react.js written: ${bytes} bytes`)