#!/usr/bin/env node
// @ts-check
/**
 * dsh-hud — build `media/xterm.js`, the terminal the SSH card renders into.
 *
 * Same shape as `tools/bundle-react.mjs`, and for the same reason: a VS Code
 * webview has no module table, so the two module namespaces plus the terminal's own
 * stylesheet are bundled into one classic script and published on
 * `globalThis.__hudXterm`. The card, which runs inside the vendor's shell, reads
 * them from there.
 *
 * The stylesheet is bundled as TEXT and injected by the card rather than dropped
 * into `media/theme.css`, because the document's CSP stamps a nonce on every
 * `<style>` the runtime creates — a bundled string gets one for free, while a
 * separate `<link>` would need the webview URI plumbing for one file.
 *
 *   node tools/bundle-xterm.mjs
 */

import { mkdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(root, 'tools', 'xterm-entry.js')
const OUT = join(root, 'media', 'xterm.js')

const entrySource = `// GENERATED by tools/bundle-xterm.mjs — the SSH card's terminal.
import { Terminal } from '@xterm/xterm'
import { FitAddon } from '@xterm/addon-fit'
import css from '@xterm/xterm/css/xterm.css'

globalThis.__hudXterm = { Terminal, FitAddon, css }
`
mkdirSync(dirname(ENTRY), { recursive: true })
writeFileSync(ENTRY, entrySource, 'utf8')

await build({
  entryPoints: [ENTRY],
  outfile: OUT,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome110'],
  minify: true,
  // xterm's licence travels with the copy, the same rule React's does.
  legalComments: 'eof',
  banner: {
    js: [
      '/*!',
      ' * dsh-hud — the SSH card\'s terminal, generated by tools/bundle-xterm.mjs.',
      ' *',
      ' * Bundles, unmodified:',
      ' *   @xterm/xterm, @xterm/addon-fit — MIT, Copyright (c) 2017-2024 The xterm.js authors',
      ' *',
      ' * Full text: THIRD-PARTY-NOTICES.md in this extension.',
      ' */',
    ].join('\n'),
  },
  // xterm ships its CSS as a file, not as a module — read as text and inject.
  loader: { '.css': 'text' },
  logLevel: 'warning',
})

console.log(`media/xterm.js written: ${statSync(OUT).size} bytes`)